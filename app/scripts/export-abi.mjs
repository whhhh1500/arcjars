// Copies the ABIs from the Foundry build into src/abi.ts (run after `forge build`).
import { readFileSync, writeFileSync } from "node:fs";
const out = new URL("../../contracts/out/", import.meta.url);
const pick = (f, c) => JSON.parse(readFileSync(new URL(`${f}/${c}.json`, out))).abi;
const src = `// Generated by scripts/export-abi.mjs from contracts/out. Do not edit.
export const arcJarAbi = ${JSON.stringify(pick("ArcJar.sol", "ArcJar"))} as const;
export const factoryAbi = ${JSON.stringify(pick("ArcJarFactory.sol", "ArcJarFactory"))} as const;
`;
writeFileSync(new URL("../src/abi.ts", import.meta.url), src);
console.log("wrote src/abi.ts");
