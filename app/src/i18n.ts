const dict = { en, zh };
const urlLang = new URLSearchParams(location.search).get("lang");
let lang: Lang = (urlLang === "zh" || urlLang === "en" ? urlLang : null) || (localStorage.getItem("arcjars.lang") as Lang) || (navigator.language.startsWith("zh") ? "zh" : "en");

export const t = (k: keyof typeof en) => dict[lang][k];
export const getLang = () => lang;
export function setLang(l: Lang) {
  lang = l;
  localStorage.setItem("arcjars.lang", l);
}
